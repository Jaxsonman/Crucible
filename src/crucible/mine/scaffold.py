"""Scaffold a mined task and re-prove its check.

`scaffold_task_dir` writes everything but the prose; `prove_task` runs the finished task's own
`check.sh` against base (must fail) and merge (must pass). Never calls `claude`.
"""

import json
import re
import shlex
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from crucible import checker, paths, workspace
from crucible.mine import verify
from crucible.mine.candidates import Candidate
from crucible.mine.config import Suite
from crucible.task import ID_RE, Task, repo_relative, repo_task_md

MINE_META = ".mine.json"
SETUP_FAILED = "crucible-check: setup failed"
SETUP_EXIT = 97
DEFAULT_TIMEOUT_MINUTES = 30
DEFAULT_MAX_TURNS = 100
LOG_TAIL = 40


class ScaffoldError(Exception):
    pass


# --- scaffold ---

def default_slug(c: Candidate) -> str:
    """`pr-<n>-<kebab title>` (`commit-<sha>-...` for a candidate without a PR number), cut to
    the task id rules."""
    # A local candidate's id is the PR number parsed from its subject, else the short merge sha.
    has_pr = not c.source.startswith("commit:") or c.id != c.merge[:8]
    prefix = "pr" if has_pr else "commit"
    kebab = re.sub(r"[^a-z0-9]+", "-", c.title.lower()).strip("-")
    slug = f"{prefix}-{c.id.lower()}-{kebab}"[:64].rstrip("-")
    return slug if ID_RE.match(slug) else f"{prefix}-{re.sub(r'[^a-z0-9]', '', c.id.lower())}"


def _suite_prelude(suite: Suite) -> list[str]:
    lines = [f"export {k}={shlex.quote(v)}" for k, v in suite.env.items()]
    lines.append(f"cd -- {shlex.quote(suite.cwd)} || exit 98" if suite.cwd != "." else "cd . || exit 98")
    return lines


def _collect_rc() -> str:
    """The shell line that keeps the first non-zero exit code of the last command (`$code`)."""
    return '[ "$code" -ne 0 ] && [ "$rc" -eq 0 ] && rc=$code'


def check_script(suites: Suite | list[Suite], runnable: list[str]) -> str:
    """The task's `check.sh`: self-contained, run with the workspace as cwd. It installs the
    hidden tests once, then for each suite runs exactly the setup and test command `verify`
    ran (`bash -c`, same placeholder filling, only that suite's runnable files). One suite
    exec's its test command. Several suites each run in a subshell (own env and cwd); a setup
    failure exits 97 at once, test failures are collected so every suite runs, and the script
    exits with the first failing code. A suite's optional regression_command runs after its tests
    in the same cwd and env."""
    suites = verify.as_suites(suites)
    plan = verify.suite_plan_for(suites, runnable)
    names = ", ".join(repr(s.name) for s in suites)
    lines = [
        "#!/usr/bin/env bash",
        f"# Generated by `crucible mine scaffold` from suite(s) {names}.",
        "# Run with the workspace as cwd; installs the hidden tests, then runs each suite's own test command.",
        "set -u -o pipefail",
        'WS="$PWD"',
        'TASK_DIR="${CRUCIBLE_TASK_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"',
        'HIDDEN="$TASK_DIR/hidden_tests"',
        '( cd "$HIDDEN" && tar -cf - --exclude=DELETED . ) | tar -xf - -C "$WS" || {',
        '  echo "crucible-check: could not install hidden tests" >&2; exit 98; }',
        'if [ -f "$HIDDEN/DELETED" ]; then',
        '  while IFS= read -r f || [ -n "$f" ]; do',
        '    [ -n "$f" ] && rm -f -- "$WS/$f"',
        '  done < "$HIDDEN/DELETED"',
        "fi",
    ]
    if len(suites) == 1:
        suite = suites[0]
        lines += _suite_prelude(suite)
        if suite.setup:
            lines.append(f'bash -c {shlex.quote(suite.setup)} || {{ echo "{SETUP_FAILED}" >&2; '
                         f"exit {SETUP_EXIT}; }}")
        test_cmd = verify.build_command(suite, runnable)
        if not suite.regression_command:
            lines.append(f"exec bash -c {shlex.quote(test_cmd)}")
            return "\n".join(lines) + "\n"
        lines.append(f"bash -c {shlex.quote(test_cmd)}; rc=$?")
        lines.append(f"echo {shlex.quote(f'== regression {suite.name} ==')}")
        lines.append(f"bash -c {shlex.quote(suite.regression_command)}; code=$?")
        lines.append(_collect_rc())
        lines.append('exit "$rc"')
        return "\n".join(lines) + "\n"
    lines.append("rc=0")
    for suite, files in plan:
        pre = "; ".join(_suite_prelude(suite))
        lines.append(f"echo {shlex.quote(f'== suite {suite.name} ==')}")
        if suite.setup:
            lines.append(f"( {pre}; bash -c {shlex.quote(suite.setup)} ) || {{ "
                         f'echo {shlex.quote(f"{SETUP_FAILED} ({suite.name})")} >&2; exit {SETUP_EXIT}; }}')
        cmd = verify.build_command(suite, files)
        lines.append(f"( {pre}; bash -c {shlex.quote(cmd)} ); code=$?")
        lines.append(_collect_rc())
        if suite.regression_command:
            lines.append(f"echo {shlex.quote(f'== regression {suite.name} ==')}")
            lines.append(
                f"( {pre}; bash -c {shlex.quote(suite.regression_command)} ); code=$?")
            lines.append(_collect_rc())
    lines.append('exit "$rc"')
    return "\n".join(lines) + "\n"


def _write_hidden_tests(repo: Path, c: Candidate, dest: Path) -> None:
    dest.mkdir()
    live = [f.path for f in c.test_files if f.status != "deleted"]
    modes = verify.blob_modes(repo, c.merge, live)
    for path in live:
        try:
            verify.write_blob(repo, c.merge, path, modes.get(path, "100644"), dest / path, dest)
        except verify.UnsafePathError as e:
            raise ScaffoldError(f"{verify.UNSAFE_PATH}: {e}") from e
    deleted = [f.path for f in c.test_files if f.status == "deleted"]
    if deleted:
        (dest / "DELETED").write_text("\n".join(deleted) + "\n", encoding="utf-8")


def scaffold_task_dir(
    repo: Path, c: Candidate, suites: Suite | list[Suite], tasks_dir: Path, *, slug: str | None = None,
    kind: str | None = None,
) -> Path:
    """Create `<tasks_dir>/<slug>/` for a verified candidate. Raises ScaffoldError (and leaves
    nothing behind) if the slug is invalid or taken."""
    suites = verify.involved_suites(c, suites)
    slug = slug or default_slug(c)
    if not ID_RE.match(slug):
        raise ScaffoldError(f"invalid task id {slug!r}: must match {ID_RE.pattern}")
    if not verify.runnable_files(c):
        raise ScaffoldError("candidate has no runnable test files")
    tasks_dir = tasks_dir.resolve()
    task_dir = tasks_dir / slug
    if task_dir.exists():
        raise ScaffoldError(f"{task_dir} already exists; refusing to overwrite")
    tasks_dir.mkdir(parents=True, exist_ok=True)
    task_dir.mkdir()
    try:
        extra = (f"source: {json.dumps(c.source)}\n"
                 + (f"source_lines: {c.size}\n" if c.size > 0 else "")
                 + f"timeout_minutes: {DEFAULT_TIMEOUT_MINUTES}\nmax_turns: {DEFAULT_MAX_TURNS}\n")
        (task_dir / "task.md").write_text(
            repo_task_md(slug, repo_relative(repo.resolve(), task_dir), c.base,
                         kind or c.suggested_kind, extra),
            encoding="utf-8")
        _write_hidden_tests(repo, c, task_dir / "hidden_tests")
        check = task_dir / "check.sh"
        check.write_text(check_script(suites, verify.runnable_files(c)), encoding="utf-8")
        check.chmod(0o755)
        (task_dir / MINE_META).write_text(json.dumps({
            "id": c.id, "base": c.base, "merge": c.merge, "suite": suites[0].name,
            "suites": [s.name for s in suites], "source": c.source}, indent=2) + "\n", encoding="utf-8")
    except BaseException:
        shutil.rmtree(task_dir, ignore_errors=True)
        raise
    return task_dir


# --- prove ---

@dataclass
class ProveResult:
    ok: bool
    task_id: str
    failure: str = ""  # e.g. "passes at base"
    log: str = ""

    def tail(self) -> str:
        return "\n".join(self.log.rstrip("\n").splitlines()[-LOG_TAIL:])


def merge_sha(task: Task) -> str:
    """The merge commit a mined task came from: `.mine.json`, a `commit:` source, or (older
    tasks) the verify cache entry for the PR number in the source URL whose base is `ref`."""
    try:
        meta = json.loads((task.task_dir / MINE_META).read_text(encoding="utf-8"))
        if meta.get("source") in (None, task.source) and meta.get("merge"):
            return str(meta["merge"])
    except (OSError, ValueError, AttributeError):
        pass
    if not task.source:
        raise ScaffoldError("task has no `source:`; cannot find the merge commit to prove against")
    if task.source.startswith("commit:"):
        return task.source[len("commit:"):]
    m = re.search(r"/pull/(\d+)", task.source)
    if m:
        for f in sorted(verify.cache_dir().glob("*.json")):
            try:
                d = json.loads(f.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if d.get("id") == m.group(1) and d.get("base") == task.ref and d.get("merge"):
                return str(d["merge"])
    raise ScaffoldError(
        f"cannot find the merge commit for source {task.source!r} (no {MINE_META} and no "
        "verify cache entry); run `crucible mine --verify` first")


def _check_at(task: Task, ref: str, label: str, timeout: float) -> checker.CheckResult:
    root = paths.work_dir() / "mine"
    root.mkdir(parents=True, exist_ok=True)
    ws = Path(tempfile.mkdtemp(prefix=f"prove-{label}-", dir=root))
    try:
        workspace.export_tree(task.repo_path, ref, ws)
        return checker.run_check(task, ws, timeout)
    finally:
        shutil.rmtree(ws, ignore_errors=True)


def prove_task(task: Task, timeout: float = verify.DEFAULT_TIMEOUT_S) -> ProveResult:
    """Run the task's own check at `ref` (must fail) and at the merge (must pass). Raises
    ScaffoldError / WorkspaceError for problems finding the task's inputs."""
    if not task.check_path:
        raise ScaffoldError("task has no `check:`; nothing to prove")
    if not task.ref:
        raise ScaffoldError("task has no `ref`")
    merge = merge_sha(task)
    base = _check_at(task, task.ref, "base", timeout)
    if SETUP_FAILED in base.log:
        return ProveResult(False, task.id, "setup failed at base", base.log)
    if base.exit_code is None:
        return ProveResult(False, task.id, "check did not finish at base", base.log)
    if base.passed:
        return ProveResult(False, task.id, "passes at base", base.log)
    after = _check_at(task, merge, "merge", timeout)
    if not after.passed:
        why = "setup failed at merge" if SETUP_FAILED in after.log else "fails at merge"
        return ProveResult(False, task.id, why, after.log)
    return ProveResult(True, task.id)


